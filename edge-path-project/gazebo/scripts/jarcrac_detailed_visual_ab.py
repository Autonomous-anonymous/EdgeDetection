#!/usr/bin/env python3
"""Generate visual-only LiDAR A/B worlds. Original files unchanged."""
from pathlib import Path
import hashlib
import xml.etree.ElementTree as ET

SOURCE = (
    Path.home()
    / 'jarcrac_imu_experiment/jarcrac_detailed_flat.sdf'
)

VARIANTS = {
    'no_chassis_visual': {'chassis'},
    'no_track_visuals': {'track_left', 'track_right'},
    'no_vehicle_visuals': {
        'chassis', 'track_left', 'track_right'
    },
}

if not SOURCE.is_file():
    raise SystemExit('Missing detailed flat source world')

original_bytes = SOURCE.read_bytes()
original_hash = hashlib.sha256(original_bytes).hexdigest()

for variant, remove_links in VARIANTS.items():
    tree = ET.parse(SOURCE)
    world = tree.getroot().find('world')

    if world is None or world.get('name') != 'jarcrac_detailed_flat':
        raise RuntimeError('Unexpected source world')

    model = world.find("./model[@name='jarcrac']")
    if model is None:
        raise RuntimeError('Detailed JARCRAC missing')

    links = {
        link.get('name'): link
        for link in model.findall('link')
    }

    if set(links) != {
        'chassis', 'track_left', 'track_right'
    }:
        raise RuntimeError('Unexpected vehicle links')

    sensor = links['chassis'].find(
        "./sensor[@name='gpu_lidar_front']"
    )

    if (
        sensor is None
        or sensor.findtext('ray/scan/horizontal/samples') != '721'
        or sensor.findtext('ray/scan/vertical/samples') != '32'
    ):
        raise RuntimeError('Verified 3D LiDAR missing')

    old_collision_count = len(model.findall('.//collision'))
    old_sensor_count = len(model.findall('.//sensor'))
    old_plugin_count = len(model.findall('plugin'))

    removed = {}

    for name, link in links.items():
        visuals = list(link.findall('visual'))

        if name in remove_links:
            if not visuals:
                raise RuntimeError(
                    f'Expected visuals on {name}'
                )

            for visual in visuals:
                link.remove(visual)

            removed[name] = len(visuals)

    if len(model.findall('.//collision')) != old_collision_count:
        raise RuntimeError('Collision geometry changed')

    if len(model.findall('.//sensor')) != old_sensor_count:
        raise RuntimeError('Sensor count changed')

    if len(model.findall('plugin')) != old_plugin_count:
        raise RuntimeError('Drive plugins changed')

    new_name = 'jarcrac_detailed_' + variant
    world.set('name', new_name)

    target = SOURCE.parent / (new_name + '.sdf')

    ET.indent(tree, space='  ')
    tree.write(
        target,
        encoding='utf-8',
        xml_declaration=True
    )

    check = ET.parse(target).getroot().find('world')

    if check.get('name') != new_name:
        raise RuntimeError('Written world name mismatch')

    print('Generated:', target)
    print('  Removed visuals:', removed)
    print('  Collision count:', old_collision_count)
    print('  Sensor count:', old_sensor_count)
    print('  Drive plugins:', old_plugin_count)

if hashlib.sha256(SOURCE.read_bytes()).hexdigest() != original_hash:
    raise RuntimeError('Source world unexpectedly changed')

print('PASS: Source world and original model unchanged')
print('No motion commands are generated by this script.')
